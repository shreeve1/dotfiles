def make_schema(memory_dir, client_subjects=None):
    """Minimal memory/schema.json; subjects default to the canonical list."""
    (memory_dir / "schema.json").write_text(
        json.dumps(
            {
                "client_subjects": client_subjects
                if client_subjects is not None
                else [
                    "halo",
                    "365",
                    "3cx",
                    "network",
                    "backup",
                    "security",
                    "endpoints",
                    "contacts",
                    "temperature",
                ],
                "topics": ["workflows"],
                "topic_dirs": ["workflows"],
                "client_dirs": ["tickets", "projects", "procedures", "meetings", "templates"],
            }
        ),
        encoding="utf-8",
    )


class HubProcedureTests(unittest.TestCase):
    def test_generated_line_is_path_neutral(self):
        with tempfile.TemporaryDirectory() as td:
            mem = Path(td)
            make_schema(mem)
            make_client_note(mem / "clients/halo/exampleco/note.md")
            self.assertEqual(run_script(HUBS, mem).returncode, 0)
            self.assertIn(
                "Generated by the `personal-memory` skill (`hubs.py`). Do not edit by hand.",
                (mem / "clients/_hubs/exampleco.md").read_text(encoding="utf-8"),
            )

    def test_old_generated_line_is_not_drift(self):
        with tempfile.TemporaryDirectory() as td:
            mem = Path(td)
            make_schema(mem)
            make_index(mem)
            data = json.loads((mem / "schema.json").read_text(encoding="utf-8"))
            data["topic_dirs"] = ["workflows", "decisions"]
            (mem / "schema.json").write_text(json.dumps(data), encoding="utf-8")
            make_client_note(mem / "clients/halo/exampleco/note.md")
            with (mem / "index.md").open("a", encoding="utf-8") as f:
                f.write("| [hub](memory/clients/_hubs/exampleco.md) | hub | Hub. | 2026-10-10 |\n")
            self.assertEqual(run_script(INDEXES, mem).returncode, 0)
            self.assertEqual(run_script(HUBS, mem).returncode, 0)
            hub = mem / "clients/_hubs/exampleco.md"
            text = hub.read_text(encoding="utf-8")
            hub.write_text(
                "\n".join(
                    "Generated by `.agents/skills/personal-memory/hubs.py`. Do not edit by hand."
                    if line.startswith("Generated by ")
                    else line
                    for line in text.splitlines()
                )
                + "\n",
                encoding="utf-8",
            )
            proc = run_script(HUBS, mem, "--check")
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            proc = run_script(GATE, mem, "audit")
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertNotIn("hub drift", proc.stdout)
            self.assertEqual(run_script(HUBS, mem).returncode, 0)
            self.assertIn(
                "Generated by the `personal-memory` skill (`hubs.py`). Do not edit by hand.",
                hub.read_text(encoding="utf-8"),
            )

    def test_client_hub_lists_procedures(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            mem = root / "memory"
            note = mem / "clients/halo/exampleco"
            note.mkdir(parents=True)
            make_schema(mem)
            (note / "note.md").write_text("---\ntitle: Note\n---\n")
            proc = root / "clients/exampleco/procedures/365"
            proc.mkdir(parents=True)
            (proc / "mail-backup.md").write_text("# x\n")
            wanted, _ = hubs.plan(mem)
            hub = mem / "clients/_hubs/exampleco.md"
            text = wanted[hub]
            self.assertIn("## procedures\n", text)
            self.assertIn("- [mail-backup](clients/exampleco/procedures/365/mail-backup.md)", text)

    def test_project_hub_lists_readme_and_configured_document_folders(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            mem = root / "memory"
            note = mem / "projects/setup/robot"
            note.mkdir(parents=True)
            make_schema(mem, client_subjects=["setup"])
            data = json.loads((mem / "schema.json").read_text(encoding="utf-8"))
            data.update(client_folder="projects", client_dirs=["design", "procedures"])
            (mem / "schema.json").write_text(json.dumps(data), encoding="utf-8")
            (note / "note.md").write_text("---\ntitle: Setup\n---\n", encoding="utf-8")
            project = root / "projects/robot"
            for kind in ("design", "procedures", "tickets"):
                (project / kind).mkdir(parents=True)
                (project / kind / "record.md").write_text("# Record\n", encoding="utf-8")
            (project / "README.md").write_text("# Robot\n", encoding="utf-8")
            wanted, _ = hubs.plan(mem)
            text = wanted[mem / "projects/_hubs/robot.md"]
            self.assertIn("[README](projects/robot/README.md)", text)
            self.assertIn("[record](projects/robot/design/record.md)", text)
            self.assertIn("[record](projects/robot/procedures/record.md)", text)
            self.assertNotIn("projects/robot/tickets/", text)
            self.assertLess(text.index("## design"), text.index("## procedures"))

