-- Only a click changes window focus. This prevents hovered Deck background
-- windows from becoming the foreground while preserving keyboard navigation.
hl.config({
  input = {
    follow_mouse = 0,

    -- Caps Lock acts as an extra Ctrl ("nocaps" also drops its lock behaviour).
    -- This replaces Omarchy's default kb_options, which maps Caps Lock to
    -- Compose (compose:caps); the two cannot coexist on the same key.
    kb_options = "ctrl:nocaps",
  },
})

